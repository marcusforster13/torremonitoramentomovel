import {createRequire} from 'node:module';
const req = createRequire('C:/Users/marcus.leite/.claude/skills/teardown/node_modules/x.js');
const {chromium} = req('playwright');
const b = await chromium.launch({args: ['--use-angle=d3d11', '--ignore-gpu-blocklist', '--enable-gpu-rasterization']});
const p = await b.newPage({viewport: {width: 1440, height: 810}});
const errs = [];
p.on('pageerror', (e) => errs.push(e.message));
p.on('console', (m) => m.type() === 'error' && errs.push(m.text()));
await p.goto('file:///C:/Users/marcus.leite/Downloads/DV/xpto-cameras/teardown-out/dist/xpto-torre.html');
await p.waitForFunction(() => window.SIM_SHOWN, null, {timeout: 60000});
await p.waitForTimeout(5000);
await p.screenshot({path: 'teardown-out/live-1.png'});
const fps = await p.evaluate(() => new Promise((r) => { let n = 0; const t0 = performance.now(); const f = () => { n++; if (performance.now() - t0 < 2000) requestAnimationFrame(f); else r(n / 2); }; requestAnimationFrame(f); }));
console.log('fps', fps, 'tier', await p.evaluate(() => window.LIVE.tier));
// assume o controle: MONITORAR, vista PTZ, cobertura
const click = async (txt) => p.locator('.bt', {hasText: new RegExp('^' + txt + '$')}).first().click();
await click('MONITORAR');
await click('LPR');
await click('COBERTURA');
await p.waitForTimeout(3600);
await p.screenshot({path: 'teardown-out/live-2.png'});
await click('CABEÇA');
await click('EXPLODIDA');
await click('RÓTULOS');
await p.mouse.move(800, 400);
await p.mouse.down();
await p.mouse.move(700, 380, {steps: 8});
await p.mouse.up();
await p.waitForTimeout(2500);
await p.screenshot({path: 'teardown-out/live-3.png'});
console.log('errors', errs);
await b.close();
